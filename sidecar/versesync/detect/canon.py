"""Canon table: the 66 books, their OSIS ids, aliases and verse counts.

The data lives in ``data/canon.json`` (generated by ``tools/generate_canon.py`` and checked in).
Alias lookup is case- and punctuation-insensitive; aliases are normalised once at load.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from importlib import resources


def normalize_name(text: str) -> str:
    """Lower-case, turn punctuation into spaces, separate digits from letters, collapse spaces.

    ``"1Cor."``, ``"1 cor"`` and ``"1  COR"`` all become ``"1 cor"``.
    """
    out: list[str] = []
    prev_digit = False
    for ch in text.lower():
        if ch.isalnum():
            if out and out[-1] != " " and prev_digit != ch.isdigit():
                out.append(" ")
            out.append(ch)
            prev_digit = ch.isdigit()
        else:
            if out and out[-1] != " ":
                out.append(" ")
            prev_digit = False
    return "".join(out).strip()


@dataclass(frozen=True)
class Book:
    order: int
    name: str
    osis: str
    aliases: tuple[str, ...]
    verse_counts: tuple[int, ...]

    @property
    def chapter_count(self) -> int:
        return len(self.verse_counts)

    def verses_in(self, chapter: int) -> int | None:
        """Verse count of a 1-based chapter, or None if the chapter does not exist."""
        if 1 <= chapter <= len(self.verse_counts):
            return self.verse_counts[chapter - 1]
        return None


class Canon:
    def __init__(self, books: tuple[Book, ...]) -> None:
        self.books = books
        self._by_osis = {b.osis: b for b in books}
        self._by_alias: dict[str, Book] = {}
        for book in books:
            for alias in (book.name, book.osis, *book.aliases):
                self._by_alias[normalize_name(alias)] = book

    def by_osis(self, osis: str) -> Book | None:
        return self._by_osis.get(osis)

    def resolve(self, name: str) -> Book | None:
        """Resolve a spoken or written book name to a book, or None."""
        return self._by_alias.get(normalize_name(name))

    def is_valid(self, book: Book, chapter: int, verse: int | None = None) -> bool:
        count = book.verses_in(chapter)
        if count is None:
            return False
        return verse is None or 1 <= verse <= count


@lru_cache(maxsize=1)
def load_canon() -> Canon:
    raw = (resources.files("versesync.detect") / "data" / "canon.json").read_text(encoding="utf-8")
    data = json.loads(raw)
    books = tuple(
        Book(
            order=b["order"],
            name=b["name"],
            osis=b["osis"],
            aliases=tuple(b["aliases"]),
            verse_counts=tuple(b["verse_counts"]),
        )
        for b in data["books"]
    )
    return Canon(books)
